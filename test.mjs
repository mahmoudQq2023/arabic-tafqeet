import assert from 'node:assert/strict';
import { tafqeet, tafqeetAmount } from './tafqeet.js';

const cases = [
  [0, 'صفر'], [1, 'واحد'], [2, 'اثنان'], [10, 'عشرة'], [11, 'أحد عشر'], [12, 'اثنا عشر'],
  [13, 'ثلاثة عشر'], [20, 'عشرون'], [25, 'خمسة وعشرون'], [99, 'تسعة وتسعون'],
  [100, 'مائة'], [110, 'مائة وعشرة'], [200, 'مائتان'], [999, 'تسعمائة وتسعة وتسعون'],
  [1000, 'ألف'], [2000, 'ألفان'], [3000, 'ثلاثة آلاف'], [10000, 'عشرة آلاف'],
  [11000, 'أحد عشر ألفاً'], [100000, 'مائة ألف'], [103000, 'مائة وثلاثة آلاف'],
  [200000, 'مائتا ألف'], [250000, 'مائتان وخمسون ألفاً'],
  [1000000, 'مليون'], [2000000, 'مليونان'], [3000000, 'ثلاثة ملايين'],
  [1250750, 'مليون ومائتان وخمسون ألفاً وسبعمائة وخمسون'],
  [1000000000, 'مليار'],
];
for (const [n, want] of cases) assert.equal(tafqeet(n), want, `tafqeet(${n})`);

const amounts = [
  [1, 'فقط جنيه واحد لا غير'],
  [2, 'فقط جنيهان لا غير'],
  [3, 'فقط ثلاثة جنيهات لا غير'],
  [11, 'فقط أحد عشر جنيهاً لا غير'],
  [100, 'فقط مائة جنيه لا غير'],
  [200, 'فقط مائتا جنيه لا غير'],
  [2000, 'فقط ألفا جنيه لا غير'],
  [1250.5, 'فقط ألف ومائتان وخمسون جنيهاً وخمسون قرشاً لا غير'],
  [0.05, 'فقط خمسة قروش لا غير'],
];
for (const [a, want] of amounts) assert.equal(tafqeetAmount(a), want, `tafqeetAmount(${a})`);
assert.equal(tafqeetAmount(15, 'USD', { frame: false }), 'خمسة عشر دولاراً');
console.log(`ok — ${cases.length + amounts.length + 1} cases`);
